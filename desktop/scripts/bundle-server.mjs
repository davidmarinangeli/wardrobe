#!/usr/bin/env node
/**
 * Bundles ../scripts/server.mjs and everything it imports into one CommonJS
 * file, src-tauri/resources/server/server.cjs (plus server.cjs.map). The
 * native packages stay external and are installed by install-native.mjs.
 *
 *   node scripts/bundle-server.mjs [--out <dir>]
 */
import { mkdir } from "node:fs/promises";
import { builtinModules } from "node:module";
import path from "node:path";
import { build } from "esbuild";
import { ESBUILD_EXTERNALS, REPO_ROOT, SERVER_RESOURCES_DIR, formatBytes, isMain, log, readAppVersion } from "./common.mjs";

export async function bundleServer({ outDir = SERVER_RESOURCES_DIR, version = readAppVersion(), entry = path.join(REPO_ROOT, "scripts", "server.mjs") } = {}) {
  await mkdir(outDir, { recursive: true });
  const outfile = path.join(outDir, "server.cjs");
  const result = await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node24",
    external: [...ESBUILD_EXTERNALS],
    define: {
      "process.env.NODE_ENV": JSON.stringify("production"),
      WARDROBE_VERSION: JSON.stringify(version),
    },
    sourcemap: "external",
    // server.mjs reads import.meta.url only to find the repo root when it runs
    // unbundled; the bundle always receives --root (Feature 01).
    logOverride: { "empty-import-meta": "silent" },
    banner: { js: `// Wardrobe server ${version}. Generated by desktop/scripts/bundle-server.mjs; do not edit.` },
    legalComments: "linked",
    metafile: true,
    logLevel: "warning",
  });
  const output = Object.values(result.metafile.outputs).find((o) => o.entryPoint);
  const externals = new Set();
  for (const out of Object.values(result.metafile.outputs)) {
    for (const imported of out.imports || []) {
      if (imported.external && !imported.path.startsWith("node:") && !builtinModules.includes(imported.path)) externals.add(imported.path);
    }
  }
  return { outfile, version, bytes: output?.bytes ?? 0, externals: [...externals].sort() };
}

if (isMain(import.meta.url)) {
  const index = process.argv.indexOf("--out");
  const outDir = index > 0 ? path.resolve(process.argv[index + 1]) : SERVER_RESOURCES_DIR;
  bundleServer({ outDir }).then(({ outfile, version, bytes, externals }) => {
    log(`server bundle ${version} → ${outfile} (${formatBytes(bytes)}); external: ${externals.join(", ")}`);
  }, (error) => {
    process.stderr.write(`${error?.stack || error}\n`);
    process.exit(1);
  });
}
